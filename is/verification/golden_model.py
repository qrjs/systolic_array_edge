#!/usr/bin/env python3
"""
Golden Model for Systolic Array Verification
功能：实现标准的矩阵乘法，作为参考模型验证硬件设计的正确性
"""

import numpy as np
import sys

def matrix_multiply_golden(A, B):
    """
    标准矩阵乘法：C = A × B

    Args:
        A: 输入矩阵 (4x4)
        B: 权重矩阵 (4x4)

    Returns:
        C: 结果矩阵 (4x4)
    """
    return np.dot(A, B)

def test_case_1():
    """测试用例1：所有权重为1，输入为1"""
    print("=" * 60)
    print("测试用例 1: 单位矩阵测试")
    print("=" * 60)

    # 4x4 矩阵，所有元素为1
    A = np.ones((4, 4), dtype=np.int32)
    B = np.ones((4, 4), dtype=np.int32)

    C = matrix_multiply_golden(A, B)

    print("输入矩阵 A (4x4):")
    print(A)
    print("\n权重矩阵 B (4x4):")
    print(B)
    print("\n预期输出 C = A × B:")
    print(C)
    print("\n分析:")
    print("  每个元素 = 1×1 + 1×1 + 1×1 + 1×1 = 4")
    print(f"  预期结果: 所有元素应为 4")
    print(f"  实际结果: {C[0, 0]}, {C[0, 1]}, {C[0, 2]}, {C[0, 3]}")

    # 验证
    expected = 4
    if np.all(C == expected):
        print(f"✅ 测试通过: 所有元素 = {expected}")
    else:
        print(f"❌ 测试失败")

    return A, B, C

