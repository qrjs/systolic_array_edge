def export_test_vectors(A, B, C, test_name):
    """
    导出测试向量，用于 Verilog 仿真

    Args:
        A, B, C: 矩阵
        test_name: 测试名称
    """
    filename = f"test_vectors_{test_name}.txt"

    with open(filename, 'w') as f:
        f.write(f"# Test vectors for {test_name}\n")
        f.write(f"# Generated by golden_model.py\n\n")

        f.write("# 输入矩阵 A (row-major order)\n")
        for i in range(4):
            for j in range(4):
                f.write(f"{A[i,j]} ")
            f.write("\n")

        f.write("\n# 权重矩阵 B (row-major order)\n")
        for i in range(4):
            for j in range(4):
                f.write(f"{B[i,j]} ")
            f.write("\n")

        f.write("\n# 预期输出 C (row-major order)\n")
        for i in range(4):
            for j in range(4):
                f.write(f"{C[i,j]} ")
            f.write("\n")

    print(f"\n📁 测试向量已导出到: {filename}")

def generate_verilog_testbench(A, B, C, test_name):
    """
    生成 Verilog 测试平台，包含自动验证

    Args:
        A, B, C: 矩阵
        test_name: 测试名称
    """
    filename = f"auto_test_{test_name}.v"

    with open(filename, 'w') as f:
        f.write(f"""// Auto-generated testbench for {test_name}
// Generated by golden_model.py

`timescale 1ns/1ps

module auto_test_{test_name};

    parameter DATA_WIDTH = 16;
    parameter WEIGHT_WIDTH = 16;
    parameter ACC_WIDTH = 32;
    parameter CLK_PERIOD = 10;

    reg clk;
    reg rst_n;
    reg [WEIGHT_WIDTH-1:0] weight_in;
    reg weight_valid;
    reg weight_load;
    wire weight_ready;

    reg [DATA_WIDTH-1:0] input_data;
    reg input_valid;
    wire input_ready;

    wire [ACC_WIDTH*4-1:0] output_data;
    wire [3:0] output_valid;
    reg [3:0] output_ready;

    reg flush;
    wire busy;
    reg clk_enable;

    // DUT instantiation
    systolic_array_4x4 #(
        .DATA_WIDTH(DATA_WIDTH),
        .WEIGHT_WIDTH(WEIGHT_WIDTH),
        .ACC_WIDTH(ACC_WIDTH)
    ) dut (
        .clk(clk),
        .rst_n(rst_n),
        .weight_in(weight_in),
        .weight_valid(weight_valid),
        .weight_load(weight_load),
        .weight_ready(weight_ready),
        .input_data(input_data),
        .input_valid(input_valid),
        .input_ready(input_ready),
        .output_data(output_data),
        .output_valid(output_valid),
        .output_ready(output_ready),
        .flush(flush),
        .clk_enable(clk_enable),
        .busy(busy)
    );

    // Clock generation
    initial begin
        clk = 0;
        forever #(CLK_PERIOD/2) clk = ~clk;
    end

    // Golden reference values
    reg signed [ACC_WIDTH-1:0] golden_output [0:3][0:3];

    initial begin
        // Initialize golden outputs from Python model
""")

        # 填充 golden 值
        for i in range(4):
            for j in range(4):
                f.write(f"        golden_output[{i}][{j}] = 32'd{C[i,j]};\n")

        f.write("""
        // Initialize signals
        rst_n = 0;
        weight_in = 0;
        weight_valid = 0;
        weight_load = 0;
        input_data = 0;
        input_valid = 0;
        output_ready = 4'b0000;
        flush = 0;
        clk_enable = 1;

        repeat(5) @(posedge clk);
        rst_n = 1;
        repeat(2) @(posedge clk);

        $display("\\n========================================");
        $display("Automated Test: {test_name}");
        $display("========================================\\n");

        // Load weights
        $display("Loading weights...");
        weight_load = 1;
""")

        # 生成权重加载代码
        idx = 0
        for i in range(4):
            for j in range(4):
                f.write(f"        @(posedge clk); weight_in = 16'd{B[i,j]}; weight_valid = 1;\n")
                idx += 1

        f.write("""        weight_valid = 0;
        weight_load = 0;

        repeat(5) @(posedge clk);

        // Send inputs
        $display("Sending inputs...");
        output_ready = 4'b1111;
""")

        # 生成输入数据代码
        for i in range(4):
            for j in range(4):
                f.write(f"        @(posedge clk); input_data = 16'd{A[i,j]}; input_valid = 1;\n")

        f.write("""        input_valid = 0;

        // Wait for outputs
        repeat(50) @(posedge clk);

        // Verify outputs
        $display("\\n========================================");
        $display("Verification Results");
        $display("========================================");

        fork
            begin
                repeat(100) @(posedge clk);
            end
            begin
                wait(output_valid[0]);
                repeat(5) @(posedge clk);  // Wait for all outputs
            end
        join_any

        // Check each output
        integer i, j, errors;
        errors = 0;

        for (i = 0; i < 4; i = i + 1) begin
            for (j = 0; j < 4; j = j + 1) begin
                automatic logic [31:0] actual = output_data[i*32 +: 32];
                automatic logic [31:0] expected = golden_output[i][j];

                if (actual !== expected) begin
                    $display("❌ ERROR: C[%0d][%0d] = %0d (expected %0d)",
                             i, j, $signed(actual), $signed(expected));
                    errors = errors + 1;
                end else begin
                    $display("✅ OK: C[%0d][%0d] = %0d", i, j, $signed(actual));
                end
            end
        end

        $display("\\n========================================");
        if (errors == 0) begin
            $display("✅ TEST PASSED: All outputs match golden model");
        end else begin
            $display("❌ TEST FAILED: %0d mismatches detected", errors);
        end
        $display("========================================\\n");

        $finish;
    end

endmodule
""")

    print(f"📁 自动测试平台已生成: {filename}")

def main():
    """主测试流程"""
    print("=" * 60)
    print("Systolic Array Golden Model Verification")
    print("=" * 60)

    # 运行所有测试用例
    tests = [
        ("test1_identity", test_case_1),
        ("test2_constant", test_case_2),
        ("test3_random", test_case_3),
        ("test4_cnn", test_case_4),
    ]

    for name, test_func in tests:
        A, B, C = test_func()

        # 导出测试向量
        export_test_vectors(A, B, C, name)

        # 生成自动验证的 testbench
        generate_verilog_testbench(A, B, C, name)

    print("\n" + "=" * 60)
    print("Golden Model 验证完成")
    print("=" * 60)
    print("\n生成的文件:")
    print("  - test_vectors_*.txt: 测试向量文件")
    print("  - auto_test_*.v: 自动验证的测试平台")
    print("\n下一步:")
    print("  1. 使用测试向量进行仿真")
    print("  2. 运行自动测试平台")
    print("  3. 查看验证结果")

if __name__ == "__main__":
    main()
